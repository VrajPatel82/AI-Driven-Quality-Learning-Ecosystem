import { useState, useEffect } from 'react';
import { Link } from 'react-router-dom';
import { quizzesAPI, coursesAPI } from '../../services/api';
import { useAuth } from '../../context/AuthContext';
import { Icons } from '../../components/shared/Icons';
import toast from 'react-hot-toast';

export default function StudentQuiz() {
  const { user, refreshUser } = useAuth();
  const [quizzes, setQuizzes] = useState([]);
  const [courses, setCourses] = useState([]);
  const [loading, setLoading] = useState(true);
  const [search, setSearch] = useState('');
  const [page, setPage] = useState(1);
  const [pagination, setPagination] = useState({});

  useEffect(() => {
    fetchCoursesAndQuizzes();
  // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [page, search]);

  const fetchCoursesAndQuizzes = async () => {
    setLoading(true);
    try {
      await refreshUser();
      let enrolledCourses = [];
      try {
        const cRes = await coursesAPI.getAll({ limit: 50 });
        enrolledCourses = cRes.data?.data || [];
      } catch (e) {
        enrolledCourses = [];
      }

      const enrolledCourseIds = enrolledCourses.map(c => typeof c === 'string' ? c : c._id);
      setCourses(enrolledCourses);
      
      const courseParams = enrolledCourseIds.length > 0 ? enrolledCourseIds.join(',') : undefined;
      const params = { page, limit: 12, ...(courseParams ? { course: courseParams } : {}) };
      if (search) params.search = search;
      const res = await quizzesAPI.getAll(params);
      setQuizzes(res.data.data || []);
      setPagination(res.data.pagination || {});
    } catch (err) {
      toast.error('Failed to load quizzes');
    } finally {
      setLoading(false);
    }
  };

  return (
    <div className="space-y-4 sm:space-y-6">
      {/* Page Header */}
      <div>
        <h1 className="text-xl sm:text-2xl font-bold text-heading">Quizzes</h1>
        <p className="text-xs sm:text-sm text-muted mt-1">
          Interactive assessments, knowledge checks, and AI-generated practice tests.
        </p>
      </div>

      {/* Search Input Bar */}
      <div className="relative w-full">
        <Icons.Search className="absolute left-3.5 top-1/2 -translate-y-1/2 w-4 h-4 text-muted pointer-events-none" />
        <input
          type="text"
          placeholder="Search quizzes by title or topic..."
          value={search}
          onChange={e => { setSearch(e.target.value); setPage(1); }}
          className="form-input w-full pl-10 pr-9 py-2.5 min-h-[44px] text-xs sm:text-sm rounded-btn"
        />
        {search && (
          <button
            onClick={() => { setSearch(''); setPage(1); }}
            className="absolute right-3 top-1/2 -translate-y-1/2 text-muted hover:text-heading p-1 text-xs font-bold"
            aria-label="Clear search"
          >
            ✕
          </button>
        )}
      </div>

      {/* Quiz List / Grid */}
      {loading ? (
        <div className="flex flex-col justify-center items-center h-48 sm:h-56">
          <div className="animate-spin rounded-full h-9 w-9 border-b-2 border-blue-600 mb-3"></div>
          <span className="text-xs sm:text-sm text-muted">Loading quizzes...</span>
        </div>
      ) : quizzes.length === 0 ? (
        <div className="text-center py-12 px-4 bg-surface rounded-card border border-border shadow-card max-w-md mx-auto">
          <div className="w-12 h-12 mx-auto rounded-full bg-blue-50 text-blue-600 flex items-center justify-center mb-3">
            <Icons.Quiz className="w-6 h-6" />
          </div>
          <h3 className="text-heading font-semibold text-base mb-1">No quizzes available</h3>
          <p className="text-muted text-xs sm:text-sm mb-4">
            {search ? 'No quizzes match your search criteria.' : 'Check back later as new quizzes are generated by your professors.'}
          </p>
          {search && (
            <button
              onClick={() => { setSearch(''); setPage(1); }}
              className="inline-flex items-center gap-1.5 px-4 py-2 rounded-btn bg-slate-100 hover:bg-slate-200 text-heading text-xs sm:text-sm font-medium transition-colors"
            >
              Clear Search Filter
            </button>
          )}
        </div>
      ) : (
        <>
          <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-3 gap-3.5 sm:gap-4">
            {quizzes.map(quiz => {
              const isActive = quiz.isActive !== false;
              return (
                <Link
                  to={`/student/quiz/${quiz._id}`}
                  key={quiz._id}
                  className="group flex flex-col justify-between bg-surface rounded-card shadow-card border border-border p-4 sm:p-5 hover:shadow-md hover:border-blue-300 transition-all active:scale-[0.995]"
                >
                  <div>
                    {/* Top Status & Badge Bar */}
                    <div className="flex items-center justify-between gap-2">
                      <div className="flex items-center gap-2 min-w-0">
                        <div className={`w-8 h-8 rounded-lg flex items-center justify-center shrink-0 ${
                          quiz.aiGenerated ? 'bg-indigo-50 text-indigo-600' : 'bg-blue-50 text-blue-600'
                        }`}>
                          {quiz.aiGenerated ? <Icons.Bot className="w-4 h-4" /> : <Icons.FileEdit className="w-4 h-4" />}
                        </div>
                        {quiz.aiGenerated && (
                          <span className="inline-flex items-center gap-1 px-2 py-0.5 text-[11px] font-semibold bg-indigo-50 text-indigo-700 border border-indigo-200 rounded-full shrink-0">
                            AI Generated
                          </span>
                        )}
                      </div>
                      
                      <span className={`inline-flex items-center gap-1.5 px-2.5 py-0.5 text-[11px] font-semibold rounded-full shrink-0 ${
                        isActive 
                          ? 'bg-emerald-50 text-emerald-700 border border-emerald-200' 
                          : 'bg-slate-100 text-slate-600 border border-slate-200'
                      }`}>
                        <span className={`w-1.5 h-1.5 rounded-full ${isActive ? 'bg-emerald-500' : 'bg-slate-400'}`} />
                        {isActive ? 'Active' : 'Closed'}
                      </span>
                    </div>

                    {/* Quiz Title */}
                    <h3 className="font-semibold text-heading text-sm sm:text-base group-hover:text-blue-600 transition-colors mt-3 line-clamp-2 leading-snug break-words">
                      {quiz.title}
                    </h3>

                    {/* Source Lecture (if AI-generated or referenced) */}
                    {quiz.sourceLecture && (
                      <p className="text-xs text-muted mt-1.5 flex items-center gap-1.5 truncate">
                        <Icons.Book className="w-3 h-3 text-slate-400 shrink-0" />
                        <span className="truncate">From: <strong className="font-medium text-slate-700">{quiz.sourceLecture.title || quiz.sourceLecture}</strong></span>
                      </p>
                    )}

                    {/* Description */}
                    <p className="text-xs sm:text-sm text-muted mt-2 line-clamp-2 leading-relaxed break-words">
                      {quiz.description || 'Test your knowledge on key lecture topics and practical concepts.'}
                    </p>
                  </div>

                  {/* Metadata Footer */}
                  <div className="pt-3.5 mt-3.5 border-t border-border/70 flex items-center justify-between text-xs text-muted gap-2">
                    <div className="flex flex-wrap items-center gap-2 min-w-0">
                      <span className="font-medium text-slate-700 whitespace-nowrap">
                        {quiz.questions?.length || 0} Qs
                      </span>
                      <span className="text-slate-300">•</span>
                      <span className="whitespace-nowrap">
                        {quiz.timeLimit || 30} mins
                      </span>
                      {quiz.course?.name && (
                        <>
                          <span className="text-slate-300">•</span>
                          <span className="truncate max-w-[120px] font-medium text-slate-600" title={quiz.course.name}>
                            {quiz.course.name}
                          </span>
                        </>
                      )}
                      {quiz.academicTerm && quiz.academicTerm !== 'CURRENT' && (
                        <>
                          <span className="text-slate-300">•</span>
                          <span className="whitespace-nowrap text-purple-600 font-medium">
                            {quiz.academicTerm}
                          </span>
                        </>
                      )}
                    </div>
                    
                    <span className="text-xs font-semibold text-blue-600 group-hover:text-blue-700 group-hover:translate-x-0.5 transition-all inline-flex items-center gap-0.5 shrink-0 whitespace-nowrap">
                      Take Quiz →
                    </span>
                  </div>
                </Link>
              );
            })}
          </div>

          {/* Pagination Controls */}
          {pagination.pages > 1 && (
            <div className="flex items-center justify-center gap-2 pt-2">
              <button
                onClick={() => setPage(p => Math.max(1, p - 1))}
                disabled={page === 1}
                className="inline-flex items-center justify-center px-4 py-2 rounded-btn border border-border bg-white hover:bg-slate-50 text-xs sm:text-sm font-medium text-heading transition-colors disabled:opacity-40 disabled:cursor-not-allowed min-h-[40px]"
              >
                Previous
              </button>
              <span className="px-3 py-1.5 text-xs sm:text-sm text-muted font-medium">
                Page {page} of {pagination.pages}
              </span>
              <button
                onClick={() => setPage(p => Math.min(pagination.pages, p + 1))}
                disabled={page >= pagination.pages}
                className="inline-flex items-center justify-center px-4 py-2 rounded-btn border border-border bg-white hover:bg-slate-50 text-xs sm:text-sm font-medium text-heading transition-colors disabled:opacity-40 disabled:cursor-not-allowed min-h-[40px]"
              >
                Next
              </button>
            </div>
          )}
        </>
      )}
    </div>
  );
}

